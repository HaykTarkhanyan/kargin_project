/**
 * Quiz content, hand-written from the curated dialogue in kargin_eng.csv in the style of the
 * fan-made Google Forms quizzes (data/google_forms/): the quoted line is the funniest beat of the
 * sketch, and the wrong options have to be jokes in their own right, usually other lines from the
 * same sketch. Stills live in public/quiz/ and are cut by scripts/extract_quiz_stills.py from
 * data/quiz/stills.json; their file names carry no video id so the URL does not give the answer away.
 * Levels are ordered easy → hard; passing one unlocks the next (see QuizGame).
 */
export interface QuizQuestion {
  prompt: string;
  /** Still shown above the prompt, a path under public/. */
  image?: string;
  options: string[];
  /** One picture per option (same length as options); rendered as a 2×2 grid. */
  optionImages?: string[];
  correctIndex: number;
  explanation?: string;
  /** The sketch the question is about; links to its page once the quiz is submitted. */
  sketchId?: string;
  /** External link shown after submit, for a video that is not in the archive. */
  link?: string;
}

export interface Quiz {
  id: string;
  level: number;
  title: string;
  difficulty: string;
  passPct: number; // fraction correct needed to pass (tunable)
  questions: QuizQuestion[];
}

